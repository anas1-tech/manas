export const toProducts = (existing = []) =>
  ROWS.map(([name, size, category, price], i) => {
    const prev = existing.find((p) => p.name === name && (p.size || '') === size);
    return {
      ...(prev || { items: [], waste_pct: 0, is_component: false, yield_qty: 1, yield_unit: 'pcs', description: '', serving_ml: null }),
      id: prev?.id || crypto.randomUUID(),
      name, size, category, sell_price: price, price_includes_vat: true, on_menu: true, sort: i + 1,
    };
  });
